static BASE: AtomicU64 = AtomicU64::new(0);
static PITCH: AtomicU64 = AtomicU64::new(0);
static COLS: AtomicU64 = AtomicU64::new(0);
static ROWS: AtomicU64 = AtomicU64::new(0);
static TOP: AtomicU64 = AtomicU64::new(0);
/// Bytes per pixel: 3 or 4.
static BYTES: AtomicU64 = AtomicU64::new(4);
/// Cursor: row << 32 | column.
static CURSOR: AtomicU64 = AtomicU64::new(0);

/// Multiboot 2 framebuffer type: direct RGB colour.
const FB_TYPE_RGB: u8 = 1;

/// Use the framebuffer at `paddr` as a console if it is a 24- or 32-bit
/// RGB one of at least 640x400 below 4 GiB. The caller checks that it is
/// not RAM.
pub fn init(paddr: u64, window_top: u64, pitch: u32, width: u32, height: u32, bpp: u8, ty: u8) -> bool {
    let size = pitch as u64 * height as u64;
    let bytes = bpp as u64 / 8;
    if ty != FB_TYPE_RGB || (bpp != 24 && bpp != 32) || width < 640 || height < 400 || (pitch as u64) < width as u64 * bytes {
        return false;
    }
    let Some(base) = mmio_ptr(paddr, size, window_top.min(1 << 32)) else { return false };
    PITCH.store(pitch as u64, Ordering::Relaxed);
    BYTES.store(bytes, Ordering::Relaxed);
    COLS.store(width as u64 / 8, Ordering::Relaxed);
    let top = height as u64 / 2 / 16;
    TOP.store(top, Ordering::Relaxed);
    ROWS.store(height as u64 / 16 - top, Ordering::Relaxed);
    CURSOR.store(0, Ordering::Relaxed);
    BASE.store(base, Ordering::Release);
    true
}

fn glyph(row: u64, col: u64, c: u8) {
    // Prints racing on the cursor never draw outside the console area.
    if row >= ROWS.load(Ordering::Relaxed) || col >= COLS.load(Ordering::Relaxed) {
        return;
    }
    let g = if (0x20..0x7f).contains(&c) { &FONT[(c - 0x20) as usize] } else { &FONT[0] };
    let base = BASE.load(Ordering::Relaxed);
    let pitch = PITCH.load(Ordering::Relaxed);
    let top = TOP.load(Ordering::Relaxed);
    let bytes = BYTES.load(Ordering::Relaxed) as usize;
    // One glyph row (8 pixels) is 24 or 32 bytes: built here, then written
    // as 64-bit words.
    let mut buf = [0u8; 32];
    for y in 0..16u64 {
        let bits = g[(y / 2) as usize];
        for x in 0..8 {
            let px: u32 = if (bits >> x) & 1 != 0 { 0x00d0_d0d0 } else { 0x0000_0040 };
            buf[x * bytes..x * bytes + bytes].copy_from_slice(&px.to_le_bytes()[..bytes]);
        }
        let line = base + ((top + row) * 16 + y) * pitch + col * 8 * bytes as u64;
        for w in 0..bytes {
            let v = u64::from_le_bytes(buf[w * 8..w * 8 + 8].try_into().unwrap());
            unsafe { core::ptr::write_unaligned((line + 8 * w as u64) as *mut u64, v) };
        }
    }
}

pub fn putc(c: u8) {
    if BASE.load(Ordering::Acquire) == 0 {
        return;
    }
    let cols = COLS.load(Ordering::Relaxed);
    let rows = ROWS.load(Ordering::Relaxed);
    let cur = CURSOR.load(Ordering::Relaxed);
    let (mut row, mut col) = (cur >> 32, cur & 0xffff_ffff);
    if c == b'\r' {
        CURSOR.store(row << 32, Ordering::Relaxed);
        return;
    }
    if c == b'\n' || col >= cols {
        col = 0;
        row = (row + 1) % rows;
        // Clear the new line and mark the one after it as the edge.
        for i in 0..cols {
            glyph(row, i, b' ');
            glyph((row + 1) % rows, i, if i % 2 == 1 { b'-' } else { b' ' });
        }
        if c == b'\n' {
            CURSOR.store(row << 32, Ordering::Relaxed);
            return;
        }
    }
    glyph(row, col, c);
    CURSOR.store(row << 32 | (col + 1), Ordering::Relaxed);
}
