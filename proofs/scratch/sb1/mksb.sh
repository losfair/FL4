cd $(dirname $0); python3 gen.py sb skipsb.txt SBK ' h0' body.lean >/dev/null || exit 1
D=../../Fl4Proofs/P3
python3 - "$D" <<'PY'
import sys,re
D=sys.argv[1]
body=open('body.lean').read()
blocks=re.split(r'\n\n(?=theorem |/--|set_option)',body)
N=4; k=(len(blocks)+N-1)//N
parts=[ '\n\n'.join(blocks[i*k:(i+1)*k]) for i in range(N)]
pre='''/- sb1: the SBK binding-frame family, part %d (generated by proofs/scratch/sb1/mksb.sh from invA/q4's gen.py: one lemma per spec function reachable from fl4KernelEntrySyscall that writes no SC/TCB binding and retypes / detypes nothing; see SpecInvSbK, SpecInvSbR). -/
import Fl4Proofs.P3.%s
open Classical

namespace Fl4Proofs.P3.SInvB
open Fl4Spec Fl4Proofs.P3.SInv

noncomputable section

set_option maxHeartbeats 1000000
set_option maxErrors 2000

variable {h0 : KHeap}

'''
post='\nend\n\nend Fl4Proofs.P3.SInvB\n'
for i in range(N):
    open(D+'/SpecInvSbF%d.lean'%(i+1),'w').write(pre%(i+1,'SpecInvSbR' if i==0 else 'SpecInvSbF%d'%i)+parts[i]+post)
PY
