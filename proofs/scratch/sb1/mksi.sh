cd $(dirname $0); python3 gen.py si skipsi.txt SIK '' bodysi.lean >/dev/null || exit 1
D=../../Fl4Proofs/P3
python3 - "$D" <<'PY'
import sys,re
D=sys.argv[1]
body=open('bodysi.lean').read()
blocks=re.split(r'\n\n(?=theorem |/--|set_option)',body)
N=6; k=(len(blocks)+N-1)//N
parts=[ '\n\n'.join(blocks[i*k:(i+1)*k]) for i in range(N)]
pre='''/- sb1: the SIK family (ScInv kept), part %d (generated by proofs/scratch/sb1/mksi.sh: the ancestors of the binding writers below the invocation shell; leaves in SpecInvSbI). -/
import Fl4Proofs.P3.%s
open Classical

namespace Fl4Proofs.P3.SInvB
open Fl4Spec Fl4Proofs.P3.SInv

noncomputable section

set_option maxHeartbeats 1000000
set_option maxErrors 2000

'''
post='\nend\n\nend Fl4Proofs.P3.SInvB\n'
for i in range(N):
    open(D+'/SpecInvSbG%d.lean'%(i+1),'w').write(pre%(i+1,'SpecInvSbI' if i==0 else 'SpecInvSbG%d'%i)+parts[i]+post)
PY
