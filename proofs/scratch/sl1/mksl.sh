#!/bin/bash
# sl1: the SL family (proofs/Fl4Proofs/P3/SpecInvSlF1..F6.lean); skip = prim.txt + caller closure of hard.txt + extra.txt
cd $(dirname $0)
python3 closure.py hard.txt extra.txt > skipSL.txt 2>closure.log || exit 1
MANUAL=manual_sl.py python3 gen.py sl skipSL.txt SLK ' Iq Kq' bodySL.lean || exit 1
D=$(cd ../../Fl4Proofs/P3; pwd)
python3 - "$D" <<'PY'
import sys,re
D=sys.argv[1]
body=open('bodySL.lean').read()
blocks=re.split(r'\n\n(?=theorem |/--|set_option)',body)
N=int(__import__('os').environ.get('NPARTS','6')); k=(len(blocks)+N-1)//N
parts=[ '\n\n'.join(blocks[i*k:(i+1)*k]) for i in range(N)]
pre='''import Fl4Proofs.P3.%s
open Classical

namespace Fl4Proofs.P3.SInvL
open Fl4Spec Fl4Proofs.P3.SInv

noncomputable section

set_option maxHeartbeats 1000000
set_option maxErrors 2000

variable {Iq : ObjRef × ObjRef} {Kq : List ObjRef}

'''
post='\nend\n\nend Fl4Proofs.P3.SInvL\n'
h1='/- sl1: the ScLive frame family `SLK I K` (SpecInvSlK) for every spec function reachable from the syscall entry outside the cap-removing / binding / decode-dependent cone (generated by proofs/scratch/sl1/mksl.sh; manual texts in manual_sl.py), part 1. -/\n'
open(D+'/SpecInvSlF1.lean','w').write(h1+pre%'SpecInvSlK'+parts[0]+post)
for i in range(1,N):
    open(D+'/SpecInvSlF%d.lean'%(i+1),'w').write('/- sl1: ScLive family lemmas, part %d (generated; see SpecInvSlF1). -/\n'%(i+1)+pre%('SpecInvSlF%d'%i)+parts[i]+post)
PY
