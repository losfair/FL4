#!/bin/bash
# sl2: the NtfnScB family (proofs/Fl4Proofs/P3/SpecInvSlN1..Nn.lean); skip = prim.txt + caller closure of hard.txt + extra.txt
cd $(dirname $0)
python3 closure.py hard.txt extra.txt > skipNB.txt 2>closure.log || exit 1
MANUAL=manual_nb.py python3 gen.py nb skipNB.txt NBK '' bodyNB.lean || exit 1
D=$(cd ../../Fl4Proofs/P3; pwd)
python3 - "$D" <<'PY'
import sys,re,os
D=sys.argv[1]
body=open('bodyNB.lean').read()
blocks=re.split(r'\n\n(?=theorem |/--|set_option)',body)
N=int(os.environ.get('NPARTS','6')); k=(len(blocks)+N-1)//N
parts=[ '\n\n'.join(blocks[i*k:(i+1)*k]) for i in range(N)]
pre='''import Fl4Proofs.P3.%s
open Classical

namespace Fl4Proofs.P3.SInvL
open Fl4Spec Fl4Proofs.P3.SInv

noncomputable section

set_option maxHeartbeats 1000000
set_option maxErrors 2000

'''
post='\nend\n\nend Fl4Proofs.P3.SInvL\n'
h1='/- sl2: the NtfnScB frame family `NBK` (SpecInvSlNK) for every spec function reachable from the syscall entry outside the signal / SC-notification binding / retype cone (generated by proofs/scratch/sl2/mknb.sh; manual texts in manual_nb.py), part 1. -/\n'
open(D+'/SpecInvSlN1.lean','w').write(h1+pre%'SpecInvSlNK'+parts[0]+post)
for i in range(1,N):
    open(D+'/SpecInvSlN%d.lean'%(i+1),'w').write('/- sl2: NtfnScB family lemmas, part %d (generated; see SpecInvSlN1). -/\n'%(i+1)+pre%('SpecInvSlN%d'%i)+parts[i]+post)
PY
